#!/usr/bin/env node
// Turns a chrome-devtools CLI snapshot (take_snapshot --filePath) into Playwright locator candidates.
//
//   node scripts/ui-context/map-locators.mjs <snapshot.txt> [--all]
//
// Output: a markdown table (role, name, Playwright locator, uniqueness, scope) to paste into
// a ui-context page map. uids are session-only and are never emitted as locators.
// By default only interactive elements, landmarks and headings are listed; --all lists every named node.

import fs from 'node:fs';

// Chrome accessibility roles -> Playwright getByRole roles (only where they differ).
const ROLE_MAP = { image: 'img', Iframe: 'iframe', RootWebArea: null, StaticText: null, LabelText: null };

const INTERACTIVE = new Set([
  'button',
  'link',
  'textbox',
  'searchbox',
  'combobox',
  'checkbox',
  'radio',
  'switch',
  'slider',
  'spinbutton',
  'option',
  'menuitem',
  'menuitemcheckbox',
  'menuitemradio',
  'tab',
  'listbox',
  'columnheader',
]);
const LANDMARKS = new Set([
  'banner',
  'main',
  'navigation',
  'region',
  'form',
  'search',
  'complementary',
  'contentinfo',
  'dialog',
  'alertdialog',
  'table',
  'list',
  'tabpanel',
  'Iframe',
  'status',
  'alert',
]);
const LISTED = (role, all) => all || INTERACTIVE.has(role) || LANDMARKS.has(role) || role === 'heading';

const LINE = /^(\s*)uid=(\S+)\s+(\S+)(?:\s+"((?:[^"\\]|\\.)*)")?(.*)$/;

const parse = (text) => {
  const nodes = [];
  const stack = [];
  for (const raw of text.split(/\r?\n/)) {
    const m = raw.match(LINE);
    if (!m) continue;
    const [, indent, uid, role, name = '', rest] = m;
    const depth = indent.length / 2;
    while (stack.length && stack[stack.length - 1].depth >= depth) stack.pop();
    const node = { uid, role, name, rest: rest.trim(), depth, parent: stack[stack.length - 1] ?? null };
    nodes.push(node);
    stack.push(node);
  }
  return nodes;
};

const pwRole = (role) => (role in ROLE_MAP ? ROLE_MAP[role] : role);
const q = (s) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

const byRole = (role, name, exact) =>
  name ? `getByRole(${q(role)}, { name: ${q(name)}${exact ? ', exact: true' : ''} })` : `getByRole(${q(role)})`;

// Nearest named landmark ancestor, used to scope ambiguous locators.
const scopeOf = (node) => {
  for (let p = node.parent; p; p = p.parent) {
    if (LANDMARKS.has(p.role) && p.name && pwRole(p.role)) return p;
  }
  return null;
};

const main = () => {
  const [file, ...flags] = process.argv.slice(2);
  if (!file) {
    console.error('usage: map-locators.mjs <snapshot.txt> [--all]');
    process.exit(1);
  }
  const all = flags.includes('--all');
  const nodes = parse(fs.readFileSync(file, 'utf8'));
  const root = nodes.find((n) => n.role === 'RootWebArea');

  const rows = [];
  for (const n of nodes) {
    const role = pwRole(n.role);
    if (!role || !LISTED(n.role, all)) continue;
    if (!n.name && !LANDMARKS.has(n.role)) continue; // unnamed controls can't be located by role+name

    const sameRole = nodes.filter((o) => o.role === n.role);
    const identical = sameRole.filter((o) => o.name === n.name).length;
    // getByRole name matching is substring + case-insensitive unless exact: true
    const substringHits = n.name
      ? sameRole.filter((o) => o.name.toLowerCase().includes(n.name.toLowerCase())).length
      : sameRole.length;
    const exact = n.name && substringHits > identical;

    // iframe is not an ARIA role Playwright accepts; frames are reached by title
    let locator =
      role === 'iframe' ? `page.getByTitle(${q(n.name)}).contentFrame()` : `page.${byRole(role, n.name, exact)}`;
    let status = 'unique';
    if (identical > 1 || (!n.name && sameRole.length > 1)) {
      const scope = scopeOf(n);
      const scopedPeers = scope
        ? nodes.filter((o) => o.role === n.role && o.name === n.name && scopeOf(o) === scope).length
        : identical;
      if (scope && scopedPeers === 1) {
        locator = `page.${byRole(pwRole(scope.role), scope.name, false)}.${byRole(role, n.name, exact)}`;
        status = `scoped (${identical} on page)`;
      } else {
        status = `AMBIGUOUS x${identical} — scope or filter manually`;
      }
    }
    const frame = (() => {
      for (let p = n.parent; p; p = p.parent) if (p.role === 'Iframe') return p;
      return null;
    })();
    if (frame) {
      locator = `page.getByTitle(${q(frame.name)}).contentFrame().${locator.replace(/^page\./, '')}`;
      status += ' · in iframe';
    }
    const scope = scopeOf(n);
    rows.push({ role, name: n.name, locator, status, within: scope ? `${pwRole(scope.role)} "${scope.name}"` : '' });
  }

  const esc = (s) => s.replace(/\|/g, '\\|');
  console.log(`<!-- generated by scripts/ui-context/map-locators.mjs from ${file.split(/[\\/]/).pop()} -->`);
  if (root) console.log(`Page: ${root.name}  \nURL: ${(root.rest.match(/url="([^"]*)"/) || [])[1] ?? ''}\n`);
  console.log('| Role | Name | Playwright locator | Uniqueness | Within |');
  console.log('|---|---|---|---|---|');
  for (const r of rows) {
    console.log(`| ${r.role} | ${esc(r.name)} | \`${esc(r.locator)}\` | ${r.status} | ${esc(r.within)} |`);
  }
  const iframes = nodes.filter((n) => n.role === 'Iframe');
  const emptyFrames = iframes.filter(
    (f) =>
      !nodes.some((o) => o.parent === f && o.role !== 'RootWebArea') &&
      nodes.filter((o) => o.parent?.parent === f).length === 0,
  );
  if (emptyFrames.length) {
    console.log(
      `\n> ${emptyFrames.length} iframe(s) have no content in the snapshot (${emptyFrames.map((f) => `"${f.name}"`).join(', ')}). ` +
        'The CLI does not descend into iframes: use evaluate_script on contentDocument (same-origin) or mark those locators "verified-by-run".',
    );
  }
};

main();
