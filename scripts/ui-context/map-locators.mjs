#!/usr/bin/env node
// Turns a chrome-devtools CLI snapshot (take_snapshot --filePath) into Playwright locator candidates.
//
//   node scripts/ui-context/map-locators.mjs <snapshot.txt> [--all]
//
// Output: a markdown table (role, name, Playwright locator, uniqueness, scope) to paste into
// a ui-context page map. uids are session-only and are never emitted as locators.
// By default only interactive elements, landmarks and headings are listed; --all lists every named node.

import fs from 'node:fs';
import { buildRows, esc, parseCdt } from './locators-core.mjs';

const main = () => {
  const [file, ...flags] = process.argv.slice(2);
  if (!file) {
    console.error('usage: map-locators.mjs <snapshot.txt> [--all]');
    process.exit(1);
  }
  const nodes = parseCdt(fs.readFileSync(file, 'utf8'));
  const root = nodes.find((n) => n.role === 'RootWebArea');
  const rows = buildRows(nodes, { all: flags.includes('--all') });

  console.log(`<!-- generated by scripts/ui-context/map-locators.mjs from ${file.split(/[\\/]/).pop()} -->`);
  if (root) console.log(`Page: ${root.name}  \nURL: ${(root.rest.match(/url="([^"]*)"/) || [])[1] ?? ''}\n`);
  console.log('| Role | Name | Playwright locator | Uniqueness | Within |');
  console.log('|---|---|---|---|---|');
  for (const r of rows) {
    console.log(`| ${r.role} | ${esc(r.name)} | \`${esc(r.locator)}\` | ${r.status} | ${esc(r.within)} |`);
  }
  const iframes = nodes.filter((n) => n.role === 'Iframe');
  const emptyFrames = iframes.filter(
    (f) =>
      !nodes.some((o) => o.parent === f && o.role !== 'RootWebArea') &&
      nodes.filter((o) => o.parent?.parent === f).length === 0,
  );
  if (emptyFrames.length) {
    console.log(
      `\n> ${emptyFrames.length} iframe(s) have no content in the snapshot (${emptyFrames.map((f) => `"${f.name}"`).join(', ')}). ` +
        'The CLI does not descend into iframes: use evaluate_script on contentDocument (same-origin) or mark those locators "verified-by-run".',
    );
  }
};

main();
